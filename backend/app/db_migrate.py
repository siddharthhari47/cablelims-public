"""
Schema migrations, driven by Alembic (see backend/alembic/) rather than the
ad-hoc column-diffing this module used to do directly (H3: the previous
version of this file walked every ORM-declared table/column, compared it
against what SQLite actually had, and issued raw `ALTER TABLE ... ADD
COLUMN` for anything missing -- an untracked, unreviewable mechanism that
ran on every single startup with no history of what it had ever changed).

Two concerns live here now:

1. Applying migrations at startup. The deployment model is a single-lab
   appliance an operator starts by double-clicking a batch file (see
   DEPLOYMENT.md) -- never a CLI. So `alembic upgrade head` still runs
   automatically on boot, same as before, but every schema change it can
   apply is now a reviewable, versioned script under alembic/versions/
   rather than a live introspect-and-ALTER loop with no audit trail.
2. Bootstrapping. A database that predates this change has a full schema
   (built by the old create_all()+sync_schema() startup pair) but no
   alembic_version table -- a naive `upgrade head` would try to
   CREATE TABLE on tables that already exist and fail. Detecting that case
   and stamping the database at the baseline revision (rather than
   replaying it) is the standard Alembic pattern for retrofitting version
   tracking onto an already-existing schema.
"""
from pathlib import Path

from alembic.config import Config
from sqlalchemy import inspect
from sqlalchemy.engine import Engine

from alembic import command

BACKEND_DIR = Path(__file__).resolve().parent.parent
ALEMBIC_INI = BACKEND_DIR / "alembic.ini"

# The first Alembic revision, generated by autogenerating against an empty
# database -- so it reproduces exactly the schema every pre-Alembic install
# already has via the old create_all()+sync_schema() pair. A database that
# already has a "users" table but no alembic_version table is, by
# definition, sitting at exactly this point and needs stamping, not replay.
BASELINE_REVISION = "69eb6322f401"


def _alembic_config(engine: Engine) -> Config:
    cfg = Config(str(ALEMBIC_INI))
    cfg.set_main_option("script_location", str(BACKEND_DIR / "alembic"))
    # Standard Alembic connection-sharing recipe: env.py checks
    # config.attributes["connection"] before falling back to building its
    # own engine from alembic.ini's sqlalchemy.url. Without this, every
    # call here would silently operate on app.db's real database
    # regardless of which `engine` was actually passed in -- fine in
    # production (main.py always passes app.db.engine, the same one), but
    # wrong as a general-purpose function signature and untestable against
    # a scratch database.
    cfg.attributes["connection"] = engine
    return cfg


def run_migrations(engine: Engine) -> str:
    """Brings the database to the latest schema. Returns a short message
    describing what happened, for the caller to log."""
    inspector = inspect(engine)
    existing_tables = set(inspector.get_table_names())
    is_pre_alembic_install = "alembic_version" not in existing_tables and "users" in existing_tables

    cfg = _alembic_config(engine)
    message = "Database schema is up to date."
    if is_pre_alembic_install:
        command.stamp(cfg, BASELINE_REVISION)
        message = f"Existing pre-Alembic database detected; stamped at baseline revision {BASELINE_REVISION}."

    command.upgrade(cfg, "head")
    return message
